"""apollo.py (#367): do the local Hessians of the identity's potential sit on Apollonian band circles?

LPS (arXiv 1208.4839 s1.2): a maximal stabilizable matrix is A = M(a,b,r+2) = 1/2 [[r+2+a, b],[b, r+2-a]] for a circle
of the band packing (strip 0<=x<=2, lines x=0, x=2, circle centre (1,0) radius 1), with center (a,b), radius r.
Integer-valued quadratics with zero Laplacian (x1 x2; x1(x1+1)/2 - x2(x2+1)/2) shift (a,b) by 2Z^2, so compare mod 2.
From a window fit A = [[A11,A12],[A12,A22]]:  a = A11-A22, b = 2 A12, r = A11+A22-2.
Packing generated by complex Descartes (Lagarias-Mallows-Wilks): C' = 2(C1+C2+C3) - C in (k, k z), lines k=0, kz=unit normal.
Control: the same (r) values with (a,b) drawn uniform in [0,2)^2 -> how often a random point lands as close to some circle.
usage: python apollo.py N [rms_max]"""
import sys
import numpy as np
N = int(sys.argv[1]); RMS = float(sys.argv[2]) if len(sys.argv) > 2 else 0.6
KMAX = 400
root = [(0.0, 1 + 0j), (0.0, -1 + 0j), (1.0, 1 + 0j), (1.0, 1 + 2j)]   # x=0, x=2, (1,0) r1, (1,2) r1
circ = {}
def add(c):
    k, kz = c
    if k > 0: circ[(round(kz.real / k, 9), round(kz.imag / k, 9), round(1 / k, 9))] = 1
for c in root: add(c)
stack = [tuple(root)]; seen = set()
while stack:
    q = stack.pop()
    for i in range(4):
        o = [q[j] for j in range(4) if j != i]
        k = 2 * sum(c[0] for c in o) - q[i][0]; kz = 2 * sum(c[1] for c in o) - q[i][1]
        if k <= q[i][0] + 1e-9 or k > KMAX: continue          # only go to smaller circles
        key = (round(k, 6), round(kz.real, 5), round(kz.imag, 5))
        if key in seen: continue
        seen.add(key); add((k, kz)); stack.append(tuple(o) + ((k, kz),))
C = np.array(list(circ.keys()))                             # x, y, r
C = C[(C[:, 1] >= -1e-9) & (C[:, 1] < 2 - 1e-9)]             # one 2-period in y
print(f"band circles with r >= {1/KMAX:.4f} in one period: {len(C)}")
H = np.load(f'out/hess_{N}.npy')                            # cy, cx, A11, A12, A22, rms, mean_e
ok = H[:, 5] <= RMS
A11, A12, A22 = H[ok, 2], H[ok, 3], H[ok, 4]
a = np.mod(A11 - A22, 2); b = np.mod(2 * A12, 2); r = A11 + A22 - 2
def nearest(a, b, r):
    best = np.full(len(a), np.inf); idx = np.zeros(len(a), int)
    for dx in (-2, 0, 2):
        for dy in (-2, 0, 2):
            d = np.sqrt((a[:, None] - C[None, :, 0] - dx)**2 + (b[:, None] - C[None, :, 1] - dy)**2 + (r[:, None] - C[None, :, 2])**2)
            j = d.argmin(1); m = d[np.arange(len(a)), j] < best
            best[m] = d[np.arange(len(a)), j][m]; idx[m] = j[m]
    am = np.minimum(np.abs(a), np.abs(2 - a)); dl = np.sqrt(am**2 + r**2)   # lines x=0, x=2 (r=0, any b)
    m = dl < best; best[m] = dl[m]; idx[m] = -1
    return best, idx
d, j = nearest(a, b, r)
rng = np.random.default_rng(367)
dc, _ = nearest(rng.uniform(0, 2, len(a)), rng.uniform(0, 2, len(a)), r)
print(f"N={N}: windows {len(H)}, periodic-looking (fit rms <= {RMS}) {ok.sum()}")
for t in (0.02, 0.05, 0.1):
    print(f"  within {t}: identity {np.mean(d < t):.3f}   control (random a,b, same r) {np.mean(dc < t):.3f}")
print(f"  median distance: identity {np.median(d):.4f}  control {np.median(dc):.4f}")
print(f"  matched to a line (trace-2 patterns): {np.mean((j == -1) & (d < 0.05)):.3f}")
u, cnt = np.unique(j[(d < 0.05) & (j >= 0)], return_counts=True)
print("  most-hit circles (x, y, r, windows):", [(*np.round(C[i], 3), int(n)) for i, n in sorted(zip(u, cnt), key=lambda z: -z[1])[:8]])
